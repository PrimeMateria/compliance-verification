use serde::Deserialize;
use std::collections::BTreeMap;
use std::fs;

#[derive(Deserialize)]
struct ErrorDef {
    name: String,
    title: String,
    description: String,
}

fn main() {
    println!("cargo:rerun-if-changed=codes.toml");

    let content = fs::read_to_string("codes.toml").expect("Failed to read codes.toml");
    let codes: BTreeMap<String, ErrorDef> =
        toml::from_str(&content).expect("Failed to parse codes.toml");

    let mut generated =
        String::from("//! AUTOGENERATED FROM codes.toml - DO NOT EDIT MANUALLY\n\n");
    generated.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq)]\npub enum OscalErrorCode {\n");

    for (code, def) in &codes {
        generated.push_str(&format!(
            "    /// {}: {}\n    {},\n",
            code, def.description, def.name
        ));
    }
    generated.push_str("}\n\nimpl OscalErrorCode {\n    pub fn as_str(&self) -> &'static str {\n        match self {\n");

    for (code, def) in &codes {
        generated.push_str(&format!(
            "            Self::{} => \"{}\",\n",
            def.name, code
        ));
    }
    generated.push_str("        }\n    }\n\n    pub fn default_title(&self) -> &'static str {\n        match self {\n");

    for def in codes.values() {
        generated.push_str(&format!(
            "            Self::{} => \"{}\",\n",
            def.name, def.title
        ));
    }
    generated.push_str("        }\n    }\n}\n");

    // Write to src/codes.rs
    fs::write("src/codes.rs", &generated).expect("Failed to write src/codes.rs");
}
